const TABLES = { REG: W_REG, MED: W_MED, BLD: W_BLD };

/**
 * 文字前進寬度（px）
 * @param {string} s
 * @param {number} size 字級
 * @param {number} weight 字重（>=700 用 Bold，>=500 用 Medium，其餘 Regular）
 */
function textWidth(s, size, weight = 400) {
  const tb = weight >= 700 ? TABLES.BLD : weight >= 500 ? TABLES.MED : TABLES.REG;
  let w = 0;
  for (const ch of String(s == null ? '' : s)) {
    const c = ch.codePointAt(0);
    if (c >= 32 && c <= 126) w += tb[c - 32];
    else w += 60;            // 非 ASCII（± – · → 等）按 0.6em 估
  }
  return w * size / 100;
}
